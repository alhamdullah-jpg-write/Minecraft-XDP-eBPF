/// Number of drop-reason slots in `struct statistics.reason[]` (xdp/stats.h).
const DROP_REASON_SLOTS: usize = 512;

// Metric name of every drop reason, indexed by its `enum drop_reason` value.
// Generated by build.rs from xdp/stats.h, which is the single source of
// truth: reasons are compared by index everywhere (the kernel masks the
// reason into struct statistics.reason[]), so the C enum and this list can
// not be allowed to drift apart. The human-readable registry - including the
// reserved names that no code path increments yet - lives in
// docs/drop-reasons.md.
include!(concat!(env!("OUT_DIR"), "/drop_reasons.rs"));

/// Name of one `enum drop_reason` value, "unknown" when out of range.
pub fn drop_reason_name(reason: u32) -> &'static str {
    DROP_REASON_NAMES
        .get(reason as usize)
        .copied()
        .unwrap_or("unknown")
}

/// Index of one `enum drop_reason` value (for statistics.reason[]).
pub fn drop_reason_index(name: &str) -> Option<usize> {
    DROP_REASON_NAMES.iter().position(|entry| *entry == name)
}

/// Userspace mirror of `struct statistics` (xdp/stats.h). Field order and
/// types must match the C struct exactly; the size assertion below mirrors
/// the `_Static_assert` in xdp/stats.h so layout drift fails the build here
/// as well as in the C build.
#[repr(C)]
#[derive(Copy, Clone, Debug)]
pub struct Statistics {
    pub verified: u64,
    pub verified_packets: u64,
    pub dropped_packets: u64,
    pub state_switches: u64,
    pub drop_connection: u64,
    pub syn: u64,
    pub tcp_bypass: u64,
    pub incoming_bytes: u64,
    pub dropped_bytes: u64,
    pub ipv6_packets: u64,
    pub udp_packets: u64,
    pub egress_errors: u64,
    pub reason: [u64; DROP_REASON_SLOTS],
}

// arrays longer than 32 elements have no derived Default; the counters all
// start at zero
impl Default for Statistics {
    fn default() -> Self {
        Statistics {
            verified: 0,
            verified_packets: 0,
            dropped_packets: 0,
            state_switches: 0,
            drop_connection: 0,
            syn: 0,
            tcp_bypass: 0,
            incoming_bytes: 0,
            dropped_bytes: 0,
            ipv6_packets: 0,
            udp_packets: 0,
            egress_errors: 0,
            reason: [0; DROP_REASON_SLOTS],
        }
    }
}

// SAFETY: repr(C) struct of plain u64 fields without padding, valid for any
// bit pattern read from the map.
unsafe impl Pod for Statistics {}

impl Statistics {
    fn add(&mut self, other: &Statistics) {
        self.verified += other.verified;
        self.verified_packets += other.verified_packets;
        self.dropped_packets += other.dropped_packets;
        self.state_switches += other.state_switches;
        self.drop_connection += other.drop_connection;
        self.syn += other.syn;
        self.tcp_bypass += other.tcp_bypass;
        self.incoming_bytes += other.incoming_bytes;
        self.dropped_bytes += other.dropped_bytes;
        self.ipv6_packets += other.ipv6_packets;
        self.udp_packets += other.udp_packets;
        self.egress_errors += other.egress_errors;
        for (total, value) in self.reason.iter_mut().zip(other.reason) {
            *total += value;
        }
    }

    /// Packets dropped for `reason` (index into the enum in xdp/stats.h).
    pub fn reason_count(&self, reason: usize) -> u64 {
        self.reason.get(reason).copied().unwrap_or(0)
    }
}

// compile-time layout check, mirrors the _Static_assert in xdp/stats.h
const _: () = assert!(std::mem::size_of::<Statistics>() == 4192);

